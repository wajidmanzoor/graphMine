// Generate from route/model definitions without starting an application server.
import {existsSync, mkdirSync, readFileSync, writeFileSync} from "node:fs";
import {fileURLToPath} from "node:url";
import {spawnSync} from "node:child_process";
import {createHash} from "node:crypto";
import openapiTS, {astToString} from "openapi-typescript";
import ts from "typescript";

const root = new URL("../../", import.meta.url);
const localPython = fileURLToPath(new URL(".venv/bin/python", root));
const python = process.env.GRAPHMINE_CONTRACT_PYTHON || (existsSync(localPython) ? localPython : "python3");
const generated = spawnSync(python, [fileURLToPath(new URL("tools/export_api_schema.py", root))], {
  cwd: fileURLToPath(root), encoding: "utf8", maxBuffer: 32 * 1024 * 1024,
  env: {...process.env, PYTHONDONTWRITEBYTECODE: "1"},
});
if (generated.error || generated.status !== 0) throw new Error(generated.error?.message || generated.stderr || "API schema export failed");
const schema = JSON.parse(generated.stdout);
const ast = await openapiTS(schema, {defaultNonNullable: false, transform(value) {
  // AnalyticsWire returns bigint for integers outside JavaScript's safe range.
  if (value.type === "integer" && !value.enum && !(Number.isSafeInteger(value.minimum) && Number.isSafeInteger(value.maximum))) {
    return ts.factory.createUnionTypeNode([ts.factory.createKeywordTypeNode(ts.SyntaxKind.NumberKeyword), ts.factory.createKeywordTypeNode(ts.SyntaxKind.BigIntKeyword)]);
  }
}});
const fingerprint = createHash("sha256").update(generated.stdout).digest("hex");
const content = `// Generated by npm run contracts. Do not edit.\n// OpenAPI SHA-256: ${fingerprint}\n// Unbounded integers use number | bigint, matching AnalyticsWire.\n\n` + astToString(ast);
const directory = new URL("generated/", import.meta.url), target = new URL("api.d.ts", directory);
if (process.argv.includes("--check")) {
  if (!existsSync(target) || readFileSync(target, "utf8") !== content) throw new Error("API contracts are stale. Run npm run contracts in agent/frontend.");
  process.stdout.write("API contracts match the current routes and models.\n");
} else {
  mkdirSync(directory, {recursive: true}); writeFileSync(target, content);
  process.stdout.write(`Generated contracts for ${Object.keys(schema.paths).length} API paths.\n`);
}
