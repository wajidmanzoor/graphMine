"""Write-once training captures that outlive the user's workspace.

Every question, model call, plan, answer and piece of feedback is appended to
its owner's capture folder. Conversations can be deleted or expire; their
captures stay, so a reviewed example can always be traced to exactly what the
model saw, which code served it and which data it ran on.

Layout under the capture root::

    deployments/<id>/deployment.json    code version, models and adapters
    deployments/<id>/tracked.patch      uncommitted changes to tracked files
    deployments/<id>/untracked.tar.gz   source files git does not track yet
    users/<owner>/sessions/<session>.jsonl   one record per line, append-only
    users/<owner>/datasets/<sha256>/    original, canonical.json, file.json
    users/<owner>/results/<workflow>-r<revision>.json

Captures are partitioned by owner so a reviewer only ever opens their own.
Writes are best effort: a capture failure never fails the user's request.
"""

from __future__ import annotations

import functools
import hashlib
import io
import json
import logging
import os
import platform
import re
import shutil
import subprocess
import tarfile
from collections.abc import Callable, Iterator
from contextlib import contextmanager
from datetime import datetime
from pathlib import Path
from threading import RLock
from typing import Any

from .models import new_id, utc_now

SCHEMA_VERSION = "graphmine-capture-v1"
# Streaming fragments are reassembled in the full reasoning event.
SKIPPED_EVENT_SUFFIXES = (".delta",)
# Saved again on every step change; only these states are worth keeping.
CAPTURED_WORKFLOW_STATES = {"awaiting_review", "ready", "completed", "failed", "cancelled"}
UNTRACKED_FILE_LIMIT = 2 * 1024 * 1024
# Model settings that identify the deployment; never credentials.
DEPLOYMENT_SETTINGS = (
    "deployment_version",
    "llm_model",
    "llm_planner_model",
    "llm_analyst_model",
    "analytics_planner_model",
    "analytics_answer_model",
    "analytics_reasoning_effort",
    "analytics_route_thinking_token_budget",
    "analytics_thinking_token_budget",
    "llm_plan_max_tokens",
    "llm_route_model",
    "llm_route_adapter_sha256",
)
DEPLOYMENT_ENVIRONMENT = (
    "GRAPHMINE_LLM_PLANNER_ADAPTER_PATH",
    "GRAPHMINE_LLM_PLANNER_ADAPTER_SHA256",
    "GRAPHMINE_LLM_ANALYST_ADAPTER_PATH",
    "GRAPHMINE_LLM_ANALYST_ADAPTER_SHA256",
)
LOCAL_OWNER = "local"
_SAFE = re.compile(r"[^A-Za-z0-9._-]")
_logger = logging.getLogger(__name__)


def _json_value(value: Any) -> Any:
    if hasattr(value, "model_dump"):
        return value.model_dump(mode="json")
    if isinstance(value, datetime):
        return value.isoformat()
    if isinstance(value, Path):
        return str(value)
    if isinstance(value, (set, frozenset)):
        return sorted(value, key=str)
    raise TypeError(f"Cannot serialize {type(value).__name__}")


def _dumps(value: Any) -> str:
    return json.dumps(value, default=_json_value, ensure_ascii=False, separators=(",", ":"))


def _name(value: str) -> str:
    # Identifiers are generated by the service; this only keeps paths inert.
    return _SAFE.sub("_", value)[:128] or "_"


def _git(root: Path, *args: str) -> bytes | None:
    try:
        return subprocess.run(
            ["git", "-C", str(root), *args],
            capture_output=True, check=True, timeout=20,
        ).stdout
    except (OSError, subprocess.SubprocessError):
        return None


@functools.lru_cache(maxsize=4)
def _source_version(root: Path) -> tuple[dict[str, Any], bytes, bytes]:
    """The commit plus every uncommitted change, so the served code is reproducible."""
    commit = _git(root, "rev-parse", "HEAD")
    if commit is None:
        return {"repository": str(root), "commit": None}, b"", b""
    patch = _git(root, "diff", "HEAD", "--binary") or b""
    listed = (_git(root, "ls-files", "--others", "--exclude-standard", "-z") or b"").split(b"\0")
    untracked, skipped, archive = [], [], io.BytesIO()
    with tarfile.open(fileobj=archive, mode="w:gz", compresslevel=6) as tar:
        for raw in filter(None, listed):
            relative = raw.decode("utf-8", "surrogateescape")
            path = root / relative
            try:
                if not path.is_file() or path.stat().st_size > UNTRACKED_FILE_LIMIT:
                    skipped.append(relative)
                    continue
                content = path.read_bytes()
            except OSError:
                skipped.append(relative)
                continue
            untracked.append({"path": relative, "sha256": hashlib.sha256(content).hexdigest()})
            info = tarfile.TarInfo(relative)
            info.size, info.mtime, info.mode = len(content), 0, 0o600
            tar.addfile(info, io.BytesIO(content))
    branch = _git(root, "rev-parse", "--abbrev-ref", "HEAD") or b""
    version = {
        "repository": str(root),
        "commit": commit.decode().strip(),
        "branch": branch.decode().strip(),
        "dirty": bool(patch or untracked),
        "patch_sha256": hashlib.sha256(patch).hexdigest(),
        "untracked": untracked,
        "untracked_skipped": skipped,
    }
    return version, patch, archive.getvalue() if untracked else b""


def deployment_snapshot(settings) -> tuple[dict[str, Any], bytes, bytes]:
    source, patch, untracked = _source_version(settings.repository_root)
    runtime = getattr(settings, "runtime_repository_root", None)
    native = None
    if runtime and runtime != settings.repository_root:
        commit = _git(runtime, "rev-parse", "HEAD")
        status = _git(runtime, "status", "--porcelain")
        native = {
            "repository": str(runtime),
            "commit": commit.decode().strip() if commit else None,
            "dirty": bool(status),
        }
    identity = _dumps([source, native, {
        name: getattr(settings, name, None) for name in DEPLOYMENT_SETTINGS
    }, {name: os.environ.get(name) for name in DEPLOYMENT_ENVIRONMENT}])
    deployment = {
        "schema_version": SCHEMA_VERSION,
        "id": hashlib.sha256(identity.encode()).hexdigest()[:20],
        "source": source,
        "native_repository": native,
        "settings": {name: getattr(settings, name, None) for name in DEPLOYMENT_SETTINGS},
        "adapters": {name: os.environ.get(name) for name in DEPLOYMENT_ENVIRONMENT},
        "host": platform.node(),
        "started_at": utc_now().isoformat(),
    }
    return deployment, patch, untracked


class TrainingCapture:
    def __init__(
        self,
        root: Path,
        *,
        owner_of: Callable[[str], dict[str, Any] | None],
        deployment: tuple[dict[str, Any], bytes, bytes] | None = None,
    ):
        self.root = root.resolve()
        self.owner_of = owner_of
        self._lock = RLock()
        self._owners: dict[str, dict[str, Any]] = {}
        self._datasets: set[tuple[str, str]] = set()
        self._used: set[tuple[str, str]] = set()
        self._failures = 0
        self.deployment_id = None
        with self.best_effort("deployment"):
            self.root.mkdir(parents=True, exist_ok=True, mode=0o700)
            # Default ACLs on shared disks can widen new folders; only the
            # service account may enter the capture root.
            self.root.chmod(0o700)
            if deployment:
                self.deployment_id = self._save_deployment(*deployment)

    @contextmanager
    def best_effort(self, problem: str) -> Iterator[None]:
        try:
            yield
        except Exception as error:  # noqa: BLE001 - the user's request continues
            with self._lock:
                self._failures += 1
                count = self._failures
            # Bounded log volume while retaining the first and latest counts.
            if count == 1 or count % 100 == 0:
                _logger.error(
                    "Training capture gap during %s (%s); %d failures since startup",
                    problem, type(error).__name__, count,
                )

    def statistics(self) -> dict[str, Any]:
        with self._lock:
            return {
                "status": "degraded" if self._failures else "ok",
                "failure_count": self._failures,
                "deployment_id": self.deployment_id,
            }

    def _save_deployment(self, deployment, patch, untracked) -> str:
        directory = self.root / "deployments" / deployment["id"]
        if not (directory / "deployment.json").is_file():
            staging = directory.with_name(f".{directory.name}.{os.getpid()}.tmp")
            shutil.rmtree(staging, ignore_errors=True)
            staging.mkdir(parents=True, mode=0o700)
            if patch:
                (staging / "tracked.patch").write_bytes(patch)
            if untracked:
                (staging / "untracked.tar.gz").write_bytes(untracked)
            (staging / "deployment.json").write_text(_dumps(deployment) + "\n", encoding="utf-8")
            try:
                staging.rename(directory)
            except OSError:
                # Another process stored the same deployment first.
                shutil.rmtree(staging, ignore_errors=True)
        return deployment["id"]

    def owner(self, session_id: str) -> dict[str, Any]:
        with self._lock:
            cached = self._owners.get(session_id)
        if cached:
            return cached
        found = self.owner_of(session_id) or {}
        owner = {"id": found.get("id") or LOCAL_OWNER, "username": found.get("username")}
        if found:
            with self._lock:
                self._owners[session_id] = owner
        return owner

    def _owner_root(self, owner: dict[str, Any]) -> Path:
        return self.root / "users" / _name(owner["id"])

    def _append(self, path: Path, line: str) -> None:
        path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
        data = (line + "\n").encode("utf-8")
        with self._lock:
            descriptor = os.open(path, os.O_WRONLY | os.O_APPEND | os.O_CREAT, 0o600)
            try:
                # One write per record keeps lines whole between processes.
                os.write(descriptor, data)
            finally:
                os.close(descriptor)

    def record(
        self,
        session_id: str,
        kind: str,
        data: Any,
        *,
        turn_id: str | None = None,
        workflow_id: str | None = None,
        job_id: str | None = None,
    ) -> None:
        with self.best_effort(kind):
            owner = self.owner(session_id)
            record = {
                "schema_version": SCHEMA_VERSION,
                "id": new_id("capture"),
                "at": utc_now().isoformat(),
                "kind": kind,
                "session_id": session_id,
                "turn_id": turn_id,
                "workflow_id": workflow_id,
                "job_id": job_id,
                "owner": owner,
                "deployment_id": self.deployment_id,
                "data": data,
            }
            path = self._owner_root(owner) / "sessions" / f"{_name(session_id)}.jsonl"
            self._append(path, _dumps(record))

    def event(self, session_id: str, kind: str, payload: dict[str, Any], *, job_id=None) -> None:
        if kind.endswith(SKIPPED_EVENT_SUFFIXES):
            return
        self.record(
            session_id, kind, payload,
            turn_id=payload.get("turn_id"),
            workflow_id=payload.get("workflow_id"),
            job_id=job_id,
        )

    def model_call(
        self,
        session_id: str,
        *,
        stage: str,
        request: dict[str, Any],
        response: Any,
        output: Any,
        outcome: str,
        seconds: float,
        error: str | None = None,
        turn_id: str | None = None,
        workflow_id: str | None = None,
        target_schema: dict[str, Any] | None = None,
        output_schema: dict[str, Any] | None = None,
    ) -> None:
        """The exact request sent and the raw response, before any parsing.

        ``target_schema`` is the full contract of the raw response (the request
        carries only the grammar hint); ``output_schema`` the decoded output's.
        A reviewed edit is checked against both, as the planner checks the model.
        """
        self.record(
            session_id,
            "model.call",
            {
                "stage": stage,
                "request": request,
                "response": response,
                "output": output,
                "outcome": outcome,
                "error": error,
                "seconds": round(seconds, 3),
                "target_schema": target_schema,
                "output_schema": output_schema,
            },
            turn_id=turn_id,
            workflow_id=workflow_id,
        )

    def workflow(self, record: dict[str, Any]) -> None:
        if record.get("status") not in CAPTURED_WORKFLOW_STATES:
            return
        self.record(
            record["session_id"],
            "workflow.saved",
            record,
            turn_id=record.get("planning_turn_id"),
            workflow_id=record.get("id"),
        )

    def dataset(self, session_id: str, file: Any, path: Path) -> None:
        """Keep the exact input once per owner, addressed by its content hash."""
        with self.best_effort("dataset"):
            owner = self.owner(session_id)
            key = (owner["id"], file.sha256)
            with self._lock:
                stored = key in self._datasets
                used = (session_id, file.sha256) in self._used
                self._used.add((session_id, file.sha256))
            if not stored:
                directory = self._owner_root(owner) / "datasets" / _name(file.sha256)
                if not (directory / "file.json").is_file():
                    staging = directory.with_name(f".{directory.name}.{os.getpid()}.tmp")
                    shutil.rmtree(staging, ignore_errors=True)
                    staging.mkdir(parents=True, mode=0o700)
                    source = Path(file.source_path) if file.source_path else None
                    if source and source.is_file():
                        shutil.copyfile(source, staging / "original")
                    shutil.copyfile(path, staging / "canonical.json")
                    (staging / "file.json").write_text(_dumps(file) + "\n", encoding="utf-8")
                    try:
                        staging.rename(directory)
                    except OSError:
                        shutil.rmtree(staging, ignore_errors=True)
                with self._lock:
                    self._datasets.add(key)
            if used:
                return
            self.record(
                session_id,
                "dataset.used",
                {
                    "file_id": file.id,
                    "sha256": file.sha256,
                    "name": file.original_name,
                    "provenance": file.provenance,
                },
            )

    def result(self, session_id: str, workflow_id: str, revision: int, saved: Any) -> None:
        with self.best_effort("result"):
            owner = self.owner(session_id)
            raw = _dumps(saved).encode("utf-8")
            path = self._owner_root(owner) / "results" / f"{_name(workflow_id)}-r{int(revision)}.json"
            if not path.is_file():
                path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
                staging = path.with_name(f".{path.name}.{os.getpid()}.tmp")
                staging.write_bytes(raw)
                staging.replace(path)
            self.record(
                session_id,
                "result.saved",
                {
                    "revision": revision,
                    "sha256": hashlib.sha256(raw).hexdigest(),
                    "size_bytes": len(raw),
                    "path": str(path.relative_to(self._owner_root(owner))),
                },
                workflow_id=workflow_id,
            )
